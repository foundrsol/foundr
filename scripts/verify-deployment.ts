import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { Connection, PublicKey } from '@solana/web3.js';
import { SolanaChain, type Deployment } from '../src/solana/chain.ts';
import { assertNetwork } from '../src/core/protocol.ts';
const binary = await readFile('program/target/deploy/shell_vault.so');
const sha = createHash('sha256').update(binary).digest('hex');
const local = JSON.parse(await readFile('.dev/svm-result.json', 'utf8'));
if (local.binarySha256 !== sha || local.passed !== true) throw Error('SVM verification must pass against this exact binary before pinning a deployment');
const manifest = JSON.parse(await readFile('public/deployment.json', 'utf8')) as Deployment;
const connection = new Connection('https://api.devnet.solana.com', 'finalized'); assertNetwork(await connection.getGenesisHash());
const program = await connection.getAccountInfo(new PublicKey(manifest.programId), 'finalized');
if (!program?.executable || program.data.length !== 36) throw Error('Program is absent or not executable');
const programData = new PublicKey(program.data.subarray(4)); const data = await connection.getAccountInfo(programData, 'finalized');
if (!data || data.data.length < 45 + binary.length) throw Error('ProgramData missing');
const authority = data.data[12] === 1 ? new PublicKey(data.data.subarray(13, 45)).toBase58() : null;
if (authority !== manifest.upgradeAuthority) throw Error('Unexpected development upgrade authority');
manifest.programData = programData.toBase58(); manifest.deploymentSlot = Number(data.data.readBigUInt64LE(4)); manifest.binarySha256 = sha; manifest.binarySize = binary.length; manifest.verified = true;
const deploy = JSON.parse(await readFile('.dev/deployment-result.json', 'utf8')); manifest.deploymentSignature = deploy.signature ?? null;
const verifier = new SolanaChain(manifest, 'https://api.devnet.solana.com'); await verifier.validate();
manifest.note = 'Bytecode, devnet genesis, slot, ProgramData and development upgrade authority verified. Experimental unaudited prototype.';
await writeFile('public/deployment.json', JSON.stringify(manifest, null, 2) + '\n'); console.log(JSON.stringify(manifest, null, 2));
